#!/usr/bin/env python3
"""Run MicroSS v2 preprocessing, temporal graph extraction, training and RCA."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from data.config import (
    MICROSS_OUTPUT_DIR,
    MICROSS_PROCESSED_DIR,
    MICROSS_RAW_DIR,
    MICROSS_WORK_DIR,
    resolve_micross_root,
)


def pipeline_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "micross_root",
        type=Path,
        nargs="?",
        default=MICROSS_RAW_DIR,
        help="MicroSS directory (default: <project>/data/MicroSS)",
    )
    parser.add_argument("--data-dir", type=Path, default=MICROSS_PROCESSED_DIR)
    parser.add_argument("--output-dir", type=Path, default=MICROSS_OUTPUT_DIR)
    parser.add_argument("--work-dir", type=Path, default=MICROSS_WORK_DIR)
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--history", type=int, default=5)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--device", choices=("auto", "cpu", "cuda", "mps"), default="auto")
    parser.add_argument("--coverage-policy", choices=("available", "complete"), default="available")
    parser.add_argument("--feature-set", choices=("all", "metric", "trace", "log",
                                                 "metric-trace", "trace-log"), default="all")
    parser.add_argument("--train-until", help="UTC date/time where validation targets begin")
    parser.add_argument("--validation-until", help="UTC date/time where test targets begin")
    parser.add_argument("--check-inputs-only", action="store_true")
    parser.add_argument("--skip-prepare", action="store_true")
    parser.add_argument("--skip-graph", action="store_true")
    parser.add_argument("--labels", type=Path, help="Label CSV generated by label_micross.py")
    parser.add_argument("--source-timezone", default="UTC")
    args = parser.parse_args()
    if min(args.epochs, args.history, args.batch_size) < 1:
        parser.error("epochs, history and batch-size must be positive")
    if bool(args.train_until) != bool(args.validation_until):
        parser.error("train-until and validation-until must be supplied together")
    return args


def pipeline_main() -> int:
    args = pipeline_args()
    root = resolve_micross_root(args.micross_root)
    data = args.data_dir.expanduser().resolve()

    def run(script, *arguments):
        command = [sys.executable, str(Path(__file__).resolve()), {"prepare_micross.py": "prepare", "build_micross_graph.py": "graph", "train_micross.py": "train"}[script], *map(str, arguments)]
        print("Running:", " ".join(command), flush=True)
        subprocess.run(command, check=True, cwd=ROOT)

    if args.check_inputs_only:
        run("prepare_micross.py", root, "--check-inputs-only",
            "--source-timezone", args.source_timezone)
        return 0
    if not args.skip_prepare:
        run("prepare_micross.py", root, "--output", data, "--source-timezone", args.source_timezone)
    schema = json.loads((data / "feature_schema.json").read_text())
    if schema.get("source_timezone", "UTC") != args.source_timezone:
        raise ValueError("source timezone differs from cached data; regenerate preprocessing")
    if schema.get("version") != 2:
        raise ValueError("pipeline requires v2 data; regenerate preprocessing outputs")
    if not args.skip_graph:
        run(
            "build_micross_graph.py",
            root / "trace/trace_split.zip",
            "--training-data-dir",
            data,
            "--output-dir",
            data,
            "--history",
            args.history,
            "--work-dir",
            args.work_dir,
        )
    run(
        "train_micross.py",
        "--data-dir",
        data,
        "--graph",
        data / "service_adjacency_1m.npz",
        "--output-dir",
        args.output_dir,
        "--epochs",
        args.epochs,
        "--history",
        args.history,
        "--batch-size",
        args.batch_size,
        "--coverage-policy",
        args.coverage_policy,
        "--feature-set",
        args.feature_set,
        *(["--train-until", args.train_until, "--validation-until", args.validation_until]
          if args.train_until and args.validation_until else []),
        "--device",
        args.device,
        "--rca-method",
        "masking",
        *(["--labels", args.labels.resolve()] if args.labels else []),
    )
    return 0



#!/usr/bin/env python3
"""Train the shared GNN-GRU pipeline on the MicroSS adapter."""




def train_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=MICROSS_PROCESSED_DIR)
    parser.add_argument("--labels", type=Path, help="Explicit label CSV; default preserves injection-start baseline")
    parser.add_argument("--adjacency-npy", "--graph", dest="adjacency_npy", type=Path)
    parser.add_argument("--rca-method", choices=("masking", "node-head"), default="masking")
    parser.add_argument("--model", choices=("gcn-gru", "gru"), default="gcn-gru")
    parser.add_argument("--output-dir", type=Path, default=MICROSS_OUTPUT_DIR)
    parser.add_argument("--history", type=int, default=5)
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--coverage-policy", choices=("available", "complete"), default="available",
                        help="Keep windows with any observed input modality, or require all service metrics")
    parser.add_argument("--feature-set", choices=("all", "metric", "trace", "log",
                                                 "metric-trace", "trace-log"), default="all")
    parser.add_argument("--train-until", help="UTC date/time where validation targets begin")
    parser.add_argument("--validation-until", help="UTC date/time where test targets begin")
    parser.add_argument("--learning-rate", type=float, default=1e-3)
    parser.add_argument("--node-loss-weight", type=float, default=1.0)
    parser.add_argument("--joint-service-pooling", action="store_true")
    parser.add_argument("--rank-loss-weight", type=float, default=0.0)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", default="auto", choices=("auto", "cpu", "mps", "cuda"))
    args = parser.parse_args()
    if args.adjacency_npy and args.adjacency_npy.suffix not in {".npy", ".npz"}:
        parser.error("graph must be a .npy static matrix or .npz temporal graph")
    if args.history < 1 or args.epochs < 1 or args.batch_size < 1:
        parser.error("history, epochs, and batch-size must be positive")
    if args.learning_rate <= 0 or min(args.node_loss_weight, args.rank_loss_weight) < 0:
        parser.error("learning-rate must be positive and loss weights nonnegative")
    if bool(args.train_until) != bool(args.validation_until):
        parser.error("train-until and validation-until must be supplied together")
    return args


def train_main() -> int:
    import numpy as np
    from constants import SERVICES
    from data.dataset import MicrossWindowDataset
    from training.experiment import run_training

    args = train_args()
    adjacency = (
        np.load(args.adjacency_npy)
        if args.adjacency_npy and args.adjacency_npy.suffix == ".npy"
        else np.eye(len(SERVICES), dtype=np.float32)
    )
    source = (
        str(args.adjacency_npy)
        if args.adjacency_npy
        else "identity matrix (no service edges); temporal-only baseline"
    )
    selected_groups = set(args.feature_set.split("-")) if args.feature_set != "all" else None
    selected_columns = None
    if selected_groups is not None:
        schema = json.loads((args.data_dir / "feature_schema.json").read_text())
        selected_columns = tuple(
            column for column in schema["feature_columns"]
            if ("metric" in selected_groups and
                (column.startswith("metric_") or column.startswith("observed_")))
            or ("trace" in selected_groups and column.startswith("trace_"))
            or ("log" in selected_groups and column.startswith("log_"))
        )
        if not selected_columns:
            raise ValueError(f"no feature columns for {args.feature_set}")
    dataset = MicrossWindowDataset(
        args.data_dir / "service_features_1m.csv",
        args.labels or args.data_dir / "next_minute_labels.csv",
        adjacency=adjacency,
        history=args.history,
        coverage_policy=args.coverage_policy,
        feature_columns=selected_columns,
        graph_path=args.adjacency_npy
        if args.adjacency_npy and args.adjacency_npy.suffix == ".npz"
        else None,
    )
    definition = "next-minute GAIA injection-start proxy"
    if args.labels:
        schema_path = args.labels.with_suffix(".schema.json")
        if not schema_path.is_file():
            raise ValueError(f"label schema missing: {schema_path}")
        definition = json.loads(schema_path.read_text())
    run_training(dataset, args, source, definition)
    return 0



